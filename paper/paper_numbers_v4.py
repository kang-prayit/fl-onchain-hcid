"""v4 macros: all v3 macros (same official CSVs, same code path as paper_numbers_v3.py) plus
v4 additions: S3-S2 gas gap (from official grid/synthetic CSVs via results/gasgap_v4), event gas per K,
and the new DAG-path IPFS test (results/ipfs_dagpath_v4). Never invents a number.
Writes numbers_macros.tex and paper_numbers_v4.txt (paper_numbers_v3.txt is not touched)."""
import os, json
import pandas as pd
HERE = os.path.dirname(os.path.abspath(__file__))
R = os.path.join(HERE, "..", "results")
src = open(os.path.join(HERE, "paper_numbers_v3.py")).read()
head, tail = src.split("# write\n", 1)
ns = {"__file__": os.path.join(HERE, "paper_numbers_v3.py"), "__name__": "v3"}
exec(compile(head, "paper_numbers_v3.py", "exec"), ns)
add, fmt_int, fmt1, G = ns["add"], ns["fmt_int"], ns["fmt1"], ns["G"]
macros, log = ns["macros"], ns["log"]
log.append("# ---- v4 additions ----")

# gas gap (table medians) and per-round decomposition
gaps = []
for k in [10, 50, 100, 500, 1000]:
    r = G[(G.k == k) & (G.variant == "storage")].set_index("label")
    gap = int(r.loc["S3 b=16", "gas_median"] - r.loc["S2", "gas_median"]); gaps.append(gap)
    add(f"GasGapK{k}", str(gap), "S3 b=16 - S2 storage median")
    e = G[(G.k == k) & (G.variant == "event")].set_index("label")
    add(f"GasEventStwoK{k}", fmt_int(e.loc["S2", "gas_median"]))
    add(f"GasEventSthreeK{k}", fmt_int(e.loc["S3 b=16", "gas_median"]))
add("GasGapMedMin", str(min(gaps))); add("GasGapMedMax", str(max(gaps)))
s = json.load(open(os.path.join(R, "gasgap_v4", "summary.json")))
assert s["resid_values"] == [22], s
add("GasGapPairs", fmt_int(s["n_round_pairs"]))
add("GasGapRoundMin", f"$-${-s['gap_min']}" if s["gap_min"] < 0 else str(s["gap_min"]))
add("GasGapRoundMax", str(s["gap_max"]))

# DAG-path test
D = os.path.join(R, "ipfs_dagpath_v4")
assert os.path.exists(os.path.join(D, "DONE"))
env = json.load(open(os.path.join(D, "env.json")))
t = pd.read_csv(os.path.join(D, "trials.csv")); w = pd.read_csv(os.path.join(D, "withhold.csv"))
KW = {100: "Konehundred", 1000: "Konethousand"}; BW = {16: "Bsixteen", 4: "Bfour"}
add("DagSizeB", fmt_int(env["update_bytes"])); add("DagTimeout", f"{env['timeout_s']:g}")
add("DagWallMin", f"{env['wall_s']/60:.1f}")
add("DagOkAll", f"{int(t.ok.sum())}/{len(t)}")
for k in [100, 1000]:
    add(f"DagNaud{KW[k]}", str(t[(t.k == k)].client.nunique()))
    for b in [16, 4]:
        nm = KW[k] + BW[b]
        for ph, pk in [("meta", "Meta"), ("full", "Full")]:
            d = t[(t.k == k) & (t.fanout == b) & (t.phase == ph)]
            add(f"Dag{pk}Med{nm}", fmt1(d.t_ms.median()))
            add(f"Dag{pk}Qone{nm}", fmt1(d.t_ms.quantile(.25)))
            add(f"Dag{pk}Qthree{nm}", fmt1(d.t_ms.quantile(.75)))
        d = t[(t.k == k) & (t.fanout == b)]
        add(f"DagOk{nm}", f"{int(d.ok.sum())}/{len(d)}")
        add(f"DagBlocks{nm}", f"{d.n_meta_blocks.median():.0f}")
        add(f"DagPath{nm}", fmt_int(d[d.phase == "meta"].meta_bytes.mean()))
        c = [x for x in env["configs"] if x["k"] == k and x["fanout"] == b][0]
        add(f"DagPinA{nm}", fmt1(c["t_pin_A_ms"])); add(f"DagBuild{nm}", fmt1(c["t_build_ms"]))
        add(f"DagDepth{nm}", str(c["depth"]))
    wk = w[w.k == k]
    add("WhN", str(wk[wk.replica == "offline"].client.nunique()))
    off = wk[wk.replica == "offline"]; on = wk[wk.replica == "online"]
    add(f"WhOffDet{KW[k]}", f"{int(off.detected.sum())}/{len(off)}")
    add(f"WhOnOk{KW[k]}", f"{int(on.ok.sum())}/{len(on)}")
    add(f"WhOnMed{KW[k]}", fmt1(on.t_ms.median()))
    add(f"WhOffMed{KW[k]}", fmt1(off.t_ms.median()))
    rw = [x for x in env["withhold"] if x["k"] == k][0]
    add(f"WhRepPin{KW[k]}", f"{rw['replica_pin_ms']/1000:.1f}")
    add(f"WhRepMiB{KW[k]}", f"{rw['replica_repo_bytes']/2**20:.0f}")

tex = ["% auto-generated by paper_numbers_v4.py (v3 macros + v4 additions) — do not edit by hand\n",
       "% names may contain digits, so they are stored via \\csname and used as \\Nm{Name}\n",
       "\\providecommand{\\Nm}[1]{\\ifcsname N#1\\endcsname\\csname N#1\\endcsname\\else\\textbf{??#1}\\fi}\n"]
for k, v in macros.items():
    tex.append(f"\\expandafter\\def\\csname N{k}\\endcsname{{{v}}}\n")
open(os.path.join(HERE, "numbers_macros.tex"), "w").write("".join(tex))
open(os.path.join(HERE, "paper_numbers_v4.txt"), "w").write("\n".join(log) + "\n")
print(f"wrote {len(macros)} macros"); print("\n".join(log[log.index('# ---- v4 additions ----'):]))
